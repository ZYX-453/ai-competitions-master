# 【这一版补全了所有维度的类目适用性，原来是漏的】
# 旧版只登记了"破损/变质/污损"一条，于是：
#   · 数码类目下出现了「按尺码表买的，上身正合身」
#   · 数码类目下出现了「材质厚实，洗了一次没变形」
# 这些文本还进了语料池，在竞品对比里表现为
# "对标在数码类目更常提 尺码/布料/合身" ——
# 分析层没错，是生成层把不同品类的语言混在了一起。
# 一个懂行的人点开原文就会发现这家"数码店"在卖衣服。
#
# 判据：这个维度在**这个品类里到底有没有可能出现**。
# 门控太严会让某个维度在某品类下消失（那是对的，数码没有"合身"），
# 门控太松则生成胡话。宁可严一点。
DIM_CAT_GATE = {
    '破损/变质/污损': {'生鲜', '个护', '数码', '服饰'},   # 所有品类都有运输磕碰
    '变质/新鲜度': {'生鲜'},                      # 只有生鲜谈新鲜度/化冻
    '尺码版型不符': {'服饰'},                    # 只有衣服有尺码版型
    '材质做工问题': {'服饰', '个护', '数码'},     # 面料/膏体/外壳都算材质
}


def _render(rng, tpl: str, cat: str, bucket: str) -> str:
    """渲染一条评论：填槽 + 同义词 + 可选前后缀。"""
    import re

    def fill(s: str) -> str:
        s = s.format(
            d=int(rng.integers(1, 9)),
            cat=str(rng.choice(CAT_WORDS[cat])),
            logi=str(rng.choice(SYN['logi'])),
            svc=str(rng.choice(SYN['svc'])),
            # 【fab 用类目专属词表，不用全局那四个】
            # 全局词表是"料子/面料/布料/材质"，放进数码类目就成
            # "手机壳的面料很薄"。按品类取词才是对的。
            fab=str(rng.choice(FAB_WORDS[cat])),
            pkg=str(rng.choice(SYN['pkg'])),
        )
        # 前缀/后缀模板里也可能带 {d}，填完主体再清一遍
        return re.sub(r'\{d\}', str(int(rng.integers(1, 9))), s)

    body = fill(tpl)

    # 【前缀只在大约一半的句子上加】
    # 每句都加会显得刻意——真实评论里很多人就是直奔主题写一句。
    # 概率取 0.5 是让两种形态各占一半，词云的共现关系也就更自然。
    pre = ''
    if rng.random() < 0.5:
        pre = fill(str(rng.choice(PRE[bucket])))
        # 前缀以逗号结尾时不要再补标点（"用了一周，料子很舒服"）
        if not pre.endswith(('，', ',', ' ')):
            pre = pre + '，'

    suf = ''
    if rng.random() < 0.45:
        suf = fill(str(rng.choice(SUF[bucket])))

    text = pre + body + suf
    # 去重标点：正文本身可能以句号结尾，后面又接"，总体还行"
    text = re.sub(r'，+', '，', text)
    return text


def build(seed: int = SEED) -> tuple[pd.DataFrame, pd.DataFrame, dict]:
    """生成竞品主数据、竞品评论、以及 DGP 真值参数。

    返回 (competitor_master, reviews, dgp)。
    """
    rng = np.random.default_rng(seed)

    # ---------- ① 竞品主数据 ----------
    rows = []
    for c in COMPETITORS:
        for cat in CATS:
            rows.append({
                'comp_id': c['comp_id'],
                'comp_name': c['name'],
                'biz_category': cat,
                'positioning': c['positioning'],
                'price_index': round(c['price_index'] * rng.uniform(0.95, 1.05), 3),
                'source': 'simulated',
                'source_note': ('按行业公开分布标定的模拟竞品，'
                                '非实时抓取。用于验证分析链路。'),
            })
    master = pd.DataFrame(rows)

    # ---------- ② 评论池 ----------
    # 【负面率是预设的真值，分析层不许读它】
    # 各竞品的负评率不同，这是"能被发现"的东西。
    # 但分析层只能从文本里判，判不出来就是判不出来。
    neg_rate = {
        'C_A': {'数码': 0.22, '生鲜': 0.26, '服饰': 0.31, '个护': 0.20},
        'C_B': {'数码': 0.14, '生鲜': 0.18, '服饰': 0.17, '个护': 0.15},
        'C_C': {'数码': 0.34, '生鲜': 0.39, '服饰': 0.42, '个护': 0.33},
        'C_D': {'数码': 0.19, '生鲜': 0.23, '服饰': 0.24, '个护': 0.18},
    }
    # 各竞品在"劣势维度"上的负评集中度（真值）
    weakness = {c['comp_id']: c['weakness'] for c in COMPETITORS}
    strength = {c['comp_id']: c['strength'] for c in COMPETITORS}

    N_PER = 260          # 每个竞品×类目 260 条，共 4*4*260 = 4160 条
    recs = []
    rid = 0
    today = date(2026, 8, 1)
    for c in COMPETITORS:
        cid = c['comp_id']
        for cat in CATS:
            n = N_PER
            n_neg_bar = neg_rate[cid][cat]
            # 用 Beta 抖动，避免每个格子都精确等于设定值（那样一看就是假的）
            p_neg = float(np.clip(rng.beta(n_neg_bar * 40, (1 - n_neg_bar) * 40), 0.05, 0.6))
            n_neg = int(round(n * p_neg))
            n_neu = int(round(n * rng.uniform(0.04, 0.10)))
            n_pos = n - n_neg - n_neu

            for bucket, cnt in (('POS', n_pos), ('NEG', n_neg), ('NEU', n_neu)):
                # 维度分布：负面时劣势维度被加权
                dims = list(NEG_TPL.keys())
                # 【按类目过掉不了的维度】
                # "生鲜收到还是冰的" 放在数码类目下就是胡话。
                # 过掉之后权重要重新归一化，否则 w.sum() < 1，
                # rng.choice 会直接抛 "probabilities do not sum to 1"。
                dims = [d for d in dims
                        if cat in DIM_CAT_GATE.get(d, {cat})]
                if bucket == 'NEG':
                    w = np.array([1.0] * len(dims))
                    for j, d in enumerate(dims):
                        if d in weakness[cid]:
                            w[j] *= 2.6
                        if d in strength[cid]:
                            w[j] *= 0.35
                    w = w / w.sum()
                else:
                    w = np.array([1.0] * len(dims)) / len(dims)

                for _ in range(cnt):
                    dim = str(rng.choice(dims, p=w))
                    pool = {'POS': POS_TPL, 'NEG': NEG_TPL, 'NEU': NEU_TPL}[bucket]
                    tpl = str(rng.choice(pool[dim]))
                    text = _render(rng, tpl, cat, bucket)
                    rid += 1
                    recs.append({
                        'review_id': f'C{rid:06d}',
                        'dataset': 'competitor',
                        'comp_id': cid,
                        'sku_id': '',
                        'biz_category': cat,
                        'review': text,
                        # 评分与情感自洽：负面 1-2 星，中性 3 星，正面 4-5 星
                        'rating': int(rng.choice([1, 2]) if bucket == 'NEG'
                                      else rng.choice([3]) if bucket == 'NEU'
                                      else rng.choice([4, 5])),
                        'label': {'POS': 1, 'NEG': 0, 'NEU': 1}[bucket],
                        'cause_l1': ('产品本体' if dim in ('材质做工问题', '破损/变质/污损',
                                                  '变质/新鲜度')
                                     else '预期管理' if dim in ('描述与实物不符', '价值感知不符', '尺码版型不符')
                                     else '服务体验' if dim in ('售后流程问题',)
                                     else '履约物流'),
                        'cause_l2': dim,
                        'week': int(rng.integers(1, 53)),
                        'review_date': (today + timedelta(days=int(rng.integers(0, 90)))).isoformat(),
                        'review_len': len(text),
                        'has_image': int(rng.random() < 0.3),
                        'truth_bucket': bucket,   # 【真值列，分析层禁止使用】
                    })

    reviews = pd.DataFrame(recs).sample(frac=1, random_state=seed).reset_index(drop=True)
    reviews['review_id'] = [f'C{i+1:06d}' for i in range(len(reviews))]

    # 实际生成的负评率（按竞品×类目），审计用它当基准
    actual_neg: dict[str, dict[str, float]] = {}
    for cid, g in reviews.groupby('comp_id'):
        actual_neg[cid] = {}
        for cat, gg in g.groupby('biz_category'):
            actual_neg[cid][cat] = round(float((gg['truth_bucket'] == 'NEG').mean()), 4)

    dgp = {
        '_meta': {
            'purpose': ('竞品评论池的生成真值。**分析层不许读这个文件**，'
                        '只供审计脚本核对"分析结果和真值差多少"。'),
            'seed': seed,
            'generated': date.today().isoformat(),
            'n_reviews': int(len(reviews)),
        },
        'competitors': [
            {'comp_id': c['comp_id'], 'name': c['name'],
             'positioning': c['positioning'],
             'strength': c['strength'], 'weakness': c['weakness']}
            for c in COMPETITORS
        ],
        # 【记录实际值，不是设定值】
        # neg_rate 是"我想让它长成什么样"，实际生成时每个格子都有 Beta 抖动，
        # 抖完之后 C_C 可能是 40.3% 而不是设定的 37%。
        # 审计脚本如果拿设定值对照，就会把"生成噪声"算成"分析误差"，
        # 于是怎么调参数都对不上。所以这里存 actual，设定值另存一份备查。
        'neg_rate_actual_by_cat': actual_neg,
        'neg_rate_target_by_cat': neg_rate,
    }
    return master, reviews, dgp


def main() -> int:
    master, reviews, dgp = build()
    os.makedirs(OUT, exist_ok=True)
    master.to_csv(os.path.join(OUT, 'competitor_master.csv'), index=False, encoding='utf-8')
    # truth_bucket 是真值，单独存一份，主表里去掉
    truth = reviews[['review_id', 'truth_bucket']].copy()
    pub = reviews.drop(columns=['truth_bucket'])
    pub.to_csv(os.path.join(OUT, 'reviews_competitor.csv'), index=False, encoding='utf-8')
    truth.to_csv(os.path.join(OUT, '_competitor_truth.csv'), index=False, encoding='utf-8')
    with open(os.path.join(OUT, 'dgp_competitor.json'), 'w', encoding='utf-8') as f:
        json.dump(dgp, f, ensure_ascii=False, indent=2)

    print(f'竞品主数据  {len(master):>6,} 行 -> competitor_master.csv')
    print(f'竞品评论    {len(reviews):>6,} 行 -> reviews_competitor.csv')
    print(f'真值对照    {len(truth):>6,} 行 -> _competitor_truth.csv（分析层禁用）')
    print()
    print('各竞品实际负评率（这是 DGP 真值，分析层要通过文本自己判）：')
    t = pub.merge(truth, on='review_id')
    for cid, g in t.groupby('comp_id'):
        neg = (g['truth_bucket'] == 'NEG').mean()
        print(f'  {cid}: {neg*100:5.1f}%   {len(g):>4,} 条')

    # 【唯一率必须打印出来】
    # 第一版没打，直到做词云才发现每个实体 1,040 条只有 82 条唯一文本。
    # 这种问题在情感分析上看不出来（准确率反而更高），
    # 只有在词云上会露馅：十几个词被放大成一整张图。
    # 所以把这个指标当成出厂检验项，低于 60% 就该警觉。
    print()
    print('文本唯一率（低于 60% 说明模板不够，词云会露馅）：')
    for cid, g in t.groupby('comp_id'):
        u = g['review'].nunique()
        print(f'  {cid}: {u:>4,} / {len(g):,}  唯一率 {u/len(g)*100:.1f}%')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())